<?php

namespace WConvert\Tests\Unit\Rest;

use PHPUnit\Framework\TestCase;
use WConvert\Destination\BulkRePush;
use WConvert\Destination\ConnectionRefused;
use WConvert\Destination\ConnectionStore;
use WConvert\Destination\DeliveryFailures;
use WConvert\Destination\DestinationRegistry;
use WConvert\Destination\DestinationStore;
use WConvert\Destination\HealthStore;
use WConvert\Destination\PushDispatcher;
use WConvert\Lead\LeadRepository;
use WConvert\Milestone\MilestoneStore;
use WConvert\Optin\OptinRepository;
use WConvert\Optin\PublishedSet;
use WConvert\Rest\DestinationController;
use WConvert\Rules\RuleVocabulary;
use WConvert\Tests\Unit\Support\FakeConnection;
use WConvert\Tests\Unit\Support\FakeDestinationType;
use WConvert\Tests\Unit\Support\FakeOptionStore;
use WConvert\Tests\Unit\Support\FakeProPresence;
use WConvert\Tests\Unit\Support\FakeQueue;
use WConvert\Tests\Unit\Support\FakeSitePresence;

/**
 * A Connection field may be generated by the server — a signing secret, the
 * site it was made on — and a Connection may carry a short list of headers.
 * A generated secret is shown exactly once; a header's value never again.
 */
final class GeneratedCredentialsTest extends TestCase
{
    private FakeOptionStore $options;
    private FakeDestinationType $type;
    private DestinationController $controller;

    protected function setUp(): void
    {
        $this->options = new FakeOptionStore();
        $this->type = new class ('hook') extends FakeDestinationType {
            /** @param array<string, mixed> $credentials */
            public function accountIdentity(array $credentials): string { return 'hooks.example'; }
        };
        $this->type->connectionSchema = [
            'url' => ['type' => 'url', 'label' => 'URL'],
            'signing_secret' => ['type' => 'secret', 'label' => 'Secret', 'prefix' => 'whsec_'],
            'headers' => ['type' => 'headers', 'label' => 'Headers', 'optional' => true, 'max' => 2, 'reserved' => ['webhook-signature', 'content-type']],
            'setup_site_url' => ['type' => 'site_url'],
        ];
        $db = new FakeConnection();
        $destinations = new DestinationStore($this->options);
        $connections = new ConnectionStore($this->options);
        $health = new HealthStore($this->options);
        $registry = (new DestinationRegistry(new FakeProPresence(), new FakeSitePresence()))->register($this->type);
        $optins = new OptinRepository($db, new PublishedSet($this->options), RuleVocabulary::fromManifest(dirname(__DIR__, 3)), new MilestoneStore($this->options));
        $this->controller = new DestinationController($registry, $destinations, $connections, $health, new DeliveryFailures($this->options),
            new BulkRePush($registry, $destinations, $optins, new LeadRepository($db), $health, new FakeQueue()),
            new PushDispatcher($registry, $destinations, $optins, $health, new FakeQueue(), $connections));
    }

    protected function tearDown(): void
    {
        unset($GLOBALS['wconvertTestQuery']['home_url']);
    }

    /** @param array<string, mixed> $params
     * @return array<string, mixed>
     */
    private function save(array $params): array
    {
        $request = new \WP_REST_Request('POST');
        foreach ($params as $key => $value) $request->set_param($key, $value);
        $response = $this->controller->saveConnection($request);
        return $response instanceof \WP_Error ? ['error' => $response->get_error_message(), 'code' => $response->get_error_code()] : $response->get_data();
    }

    /** @return array<string, mixed> */
    private function stored(string $id): array
    {
        $connection = (new ConnectionStore($this->options))->find($id);
        return $connection === null ? [] : $connection->credentials;
    }

    /** @return array<string, mixed> */
    private function created(): array
    {
        return $this->save(['type' => 'hook', 'credentials' => ['url' => 'https://hooks.example/abc',
            'headers' => [['name' => 'x-make-apikey', 'value' => 'key-1']]]]);
    }

    public function testTheSecretIsGeneratedAndShownOnceThenOnlyAsSet(): void
    {
        $GLOBALS['wconvertTestQuery']['home_url'] = 'https://shop.example';
        $created = $this->created();
        $secret = $created['revealed']['signing_secret'];
        self::assertMatchesRegularExpression('/^whsec_[A-Za-z0-9+\/]{43}=$/D', $secret);
        $id = $created['connection']['id'];
        self::assertSame($secret, $this->stored($id)['signing_secret']);
        self::assertSame('https://shop.example', $this->stored($id)['setup_site_url']);
        self::assertTrue($created['connection']['credentials']['signing_secret']);
        self::assertSame(['x-make-apikey'], $created['connection']['credentials']['headers'], 'Header names, never values.');
        self::assertStringNotContainsString('key-1', (string) json_encode($created['connection']));
        self::assertSame('hooks.example', $created['connection']['account_identity'], 'The host, so the admin can show whose it is.');

        $edited = $this->save(['id' => $id, 'credentials' => ['url' => 'https://hooks.example/def']]);
        self::assertArrayNotHasKey('revealed', $edited, 'An edit does not show the secret again.');
        self::assertSame($secret, $this->stored($id)['signing_secret']);
    }

    public function testAMerchantCannotChooseTheSecretOrTheSite(): void
    {
        $created = $this->save(['type' => 'hook', 'credentials' => ['url' => 'https://hooks.example/abc', 'signing_secret' => 'whsec_mine', 'setup_site_url' => 'https://elsewhere.example']]);
        $stored = $this->stored($created['connection']['id']);
        self::assertNotSame('whsec_mine', $stored['signing_secret']);
        self::assertSame('https://example.test', $stored['setup_site_url']);
    }

    public function testRegeneratingSwitchesTheSecretAtOnce(): void
    {
        $created = $this->created();
        $id = $created['connection']['id'];
        $request = new \WP_REST_Request('POST');
        $request->set_param('id', $id);
        $response = $this->controller->regenerateConnection($request);
        self::assertInstanceOf(\WP_REST_Response::class, $response);
        $regenerated = $response->get_data();
        self::assertNotSame($created['revealed']['signing_secret'], $regenerated['revealed']['signing_secret']);
        self::assertSame($regenerated['revealed']['signing_secret'], $this->stored($id)['signing_secret']);
        self::assertSame('https://hooks.example/abc', $this->stored($id)['url']);
    }

    public function testAHeaderKeepsItsValueWhenEditedWithoutOne(): void
    {
        $id = $this->created()['connection']['id'];
        $this->save(['id' => $id, 'credentials' => ['headers' => [['name' => 'x-make-apikey', 'value' => ''], ['name' => 'X-Extra', 'value' => 'two']]]]);
        self::assertSame([['name' => 'x-make-apikey', 'value' => 'key-1'], ['name' => 'X-Extra', 'value' => 'two']], $this->stored($id)['headers']);
        $this->save(['id' => $id, 'credentials' => ['headers' => []]]);
        self::assertSame([], $this->stored($id)['headers'], 'Removing every header is allowed.');
    }

    public function testAHeaderThatWouldForgeTheRequestIsRefused(): void
    {
        $refused = [
            [['name' => 'Webhook-Signature', 'value' => 'v1,x']],
            [['name' => 'content-type', 'value' => 'text/plain']],
            [['name' => 'Bad Name', 'value' => 'x']],
            [['name' => 'x-a', 'value' => "line\r\nInjected: 1"]],
            [['name' => 'x-new', 'value' => '']],
            [['name' => 'x-a', 'value' => '1'], ['name' => 'X-A', 'value' => '2']],
            [['name' => 'x-a', 'value' => '1'], ['name' => 'x-b', 'value' => '2'], ['name' => 'x-c', 'value' => '3']],
            'not a list',
        ];
        foreach ($refused as $headers) {
            $result = $this->save(['type' => 'hook', 'credentials' => ['url' => 'https://hooks.example/abc', 'headers' => $headers]]);
            self::assertArrayHasKey('error', $result, (string) json_encode($headers));
        }
    }

    public function testATypesOwnRefusalIsShownInItsOwnWords(): void
    {
        $this->type->connectionFailure = new ConnectionRefused('This URL points at a private network address.');
        self::assertSame('This URL points at a private network address.', $this->save(['type' => 'hook', 'credentials' => ['url' => 'http://localhost/']])['error']);
        $this->type->connectionFailure = new \RuntimeException('Vendor said: key sk_live_123 is bad');
        self::assertStringNotContainsString('sk_live', $this->save(['type' => 'hook', 'credentials' => ['url' => 'https://hooks.example/abc']])['error']);
    }

    public function testACopyOfTheSiteKnowsItIsOne(): void
    {
        $GLOBALS['wconvertTestQuery']['home_url'] = 'https://shop.example';
        $this->created();
        $read = fn (): array => $this->controller->index()->get_data();
        self::assertFalse($read()['connections'][0]['site_changed']);
        $GLOBALS['wconvertTestQuery']['home_url'] = 'https://staging.shop.example';
        self::assertTrue($read()['connections'][0]['site_changed']);
        self::assertSame('shop.example', $read()['connections'][0]['set_up_on'], 'Where it was set up, by host.');
        self::assertSame('production', $read()['environment']);
    }
}
