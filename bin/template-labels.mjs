#!/usr/bin/env node
//
// template-labels.mjs — the bundled designs' names, as PHP make-pot can read.
//
//     npm run templates:labels           write both labels.php files
//     npm run templates:labels -- --check fail where either is out of date
//
// A design's name and its screens' names are what the gallery, the builder's
// screen list and the flow map show a merchant, and they live in JSON — which
// no extractor reads. So this writes them out as literal `__()` calls, one
// file per plugin and domain, the way `resources/collections/labels.php` does
// for Collections. `WConvert\Template\TemplateNames` applies them as a design
// is loaded.
//
//   free  resources/templates/library/*.json  →  resources/templates/labels.php  ('wconvert')
//   Pro   pro/modules/*/templates/*.json      →  pro/resources/templates/labels.php  ('wconvert-pro')
//
// Generated, never edited by hand: `TemplateNamesTest` fails on a labels file
// that no longer says what the JSON says.

import { readFileSync, readdirSync, writeFileSync, existsSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');

const SETS = [
  { dirs: ['resources/templates/library'], out: 'resources/templates/labels.php', domain: 'wconvert' },
  {
    dirs: readdirSync(join(ROOT, 'pro/modules')).map((m) => `pro/modules/${m}/templates`).filter((d) => existsSync(join(ROOT, d))),
    out: 'pro/resources/templates/labels.php',
    domain: 'wconvert-pro',
  },
];

const php = (value) => `'${value.replaceAll('\\', '\\\\').replaceAll("'", "\\'")}'`;

export function labelsFile(designs, domain) {
  const call = (text, context) => `_x(${php(text)}, ${php(context)}, ${php(domain)})`;
  const lines = designs
    .sort((a, b) => a.id.localeCompare(b.id))
    .map(({ id, name, steps }) => {
      const screens = steps
        .filter((step) => typeof step.id === 'string' && typeof step.name === 'string' && step.name !== '')
        .map((step) => `${php(step.id)} => ${call(step.name, 'a screen of a campaign design')}`);
      return `    ${php(id)} => ['name' => ${call(name, 'a campaign design\'s name')}, 'steps' => [${screens.join(', ')}]],`;
    });
  return "<?php\n// Generated by bin/template-labels.mjs from the bundled designs. Do not edit.\n"
    + "defined('ABSPATH') || exit;\nreturn [\n" + lines.join('\n') + '\n];\n';
}

function designsIn(dirs) {
  return dirs.flatMap((dir) => readdirSync(join(ROOT, dir)).filter((f) => f.endsWith('.json')).map((f) => {
    const design = JSON.parse(readFileSync(join(ROOT, dir, f), 'utf8'));
    return { id: design.id, name: design.name ?? design.id, steps: design.tree?.steps ?? [] };
  }));
}

const check = process.argv.includes('--check');
let stale = 0;
for (const { dirs, out, domain } of SETS) {
  const content = labelsFile(designsIn(dirs), domain);
  const path = join(ROOT, out);
  if (check) {
    if (!existsSync(path) || readFileSync(path, 'utf8') !== content) {
      console.error(`✗ ${out} is out of date — run npm run templates:labels`);
      stale++;
    }
  } else {
    writeFileSync(path, content);
    console.log(`  ${out}`);
  }
}
if (stale > 0) process.exit(1);
if (check) console.log('✓ template labels are current');
