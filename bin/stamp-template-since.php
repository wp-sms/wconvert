<?php
/**
 * Stamp every unstamped template vocabulary entry with the current version.
 *
 * Run after adding a node, param, role, choice, token or field to
 * resources/templates/manifest.json. Existing stamps are never changed:
 * an installed reader compares against the number it shipped with (ADR 0156).
 */
define('ABSPATH', '/');
define('WCONVERT_URL', '');
$root = dirname(__DIR__);
require $root . '/src/constants.php';
require $root . '/vendor/autoload.php';
$path = $root . '/' . \WConvert\Template\Catalog\VocabularySince::PATH;
$stamps = is_file($path) ? json_decode((string) file_get_contents($path), true, 8, JSON_THROW_ON_ERROR) : [];
$stamps['_note'] = 'Generated by bin/stamp-template-since.php. The plugin version that introduced each vocabulary entry; never edit an existing stamp (ADR 0156).';
$missing = (new \WConvert\Template\Catalog\VocabularySince(\WConvert\Template\TemplateManifest::load($root), []))->missing();
foreach ($missing as $key) $stamps[$key] = WCONVERT_VERSION;
$note = $stamps['_note']; unset($stamps['_note']); ksort($stamps);
file_put_contents($path, json_encode(['_note' => $note] + $stamps, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES | JSON_UNESCAPED_UNICODE) . "\n");
fwrite(STDOUT, count($missing) . " entries stamped with " . WCONVERT_VERSION . ".\n");
