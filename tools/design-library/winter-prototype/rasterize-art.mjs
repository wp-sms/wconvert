// Authoring-only export. The prototype uses ordinary PNGs, not inline SVG shapes.
// Run: node tools/design-library/winter-prototype/rasterize-art.mjs
import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import { art } from './art.mjs';
const target = new URL('./assets/art/', import.meta.url);
await mkdir(target, { recursive: true });
const browser = await chromium.launch();
const page = await browser.newPage();
const records = [];
const labels = {
  moon: 'Cream crescent moon', flower: 'Terracotta eight-petal flower',
  flowerGreen: 'Green eight-petal flower', advent: 'Four illustrated festive tiles',
  villageWide: 'Snow-covered village panorama', ribbon: 'Wrapped Christmas gift',
  village: 'Winter cottage and pine trees', baubles: 'Three hanging ornaments',
  pine: 'Christmas tree with wrapped gifts', candles: 'Three lit candles',
  presents: 'Colourful wrapped gifts', botanical: 'Winter leaves and berries',
  envelope: 'Sealed winter letter', globe: 'Cottage inside a snowglobe',
  parcel: 'Wrapped delivery parcel', citrus: 'Christmas tree with dried oranges',
  dawn: 'Sunrise above layered hills', stars: 'Golden star on a blue background',
  book: 'Winter book with a tree on its cover', mug: 'Warm drink in a red mug',
};
try {
  for (const [key, source] of Object.entries(art)) {
    const [, w, h] = source.match(/viewBox="0 0 (\d+) (\d+)"/);
    const scale = Number(w) <= 100 ? 3 : 2.5;
    const width = Math.round(w * scale), height = Math.round(h * scale);
    const png = await page.evaluate(async ({ source, width, height }) => {
      const image = new Image();
      image.src = URL.createObjectURL(new Blob([source], { type: 'image/svg+xml' }));
      await image.decode();
      const canvas = document.createElement('canvas');
      canvas.width = width; canvas.height = height;
      canvas.getContext('2d').drawImage(image, 0, 0, width, height);
      URL.revokeObjectURL(image.src);
      return canvas.toDataURL('image/png').split(',')[1];
    }, { source, width, height });
    await writeFile(new URL(`${key}.png`, target), Buffer.from(png, 'base64'));
    const bg = source.match(/<rect width="\d+" height="\d+" fill="([^"]+)"/)?.[1] || 'transparent';
    records.push(`  ${key}: { src: new URL('./assets/art/${key}.png', import.meta.url).href, bg: '${bg}', alt: ${JSON.stringify(labels[key]||labels[key.replace('Banner','')])}, width: ${width}, height: ${height} },`);
  }
  await writeFile(new URL('./art-assets.mjs', import.meta.url), `// Generated by rasterize-art.mjs from original illustrations in art.mjs.\nexport const artwork = {\n${records.join('\n')}\n};\n`);
  console.log(`Exported ${records.length} replaceable PNG assets.`);
} finally { await browser.close(); }
